mod dist;
mod icons;

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use kvmate_protocol::{self as proto, Msg, MsgType, secure};

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let result = match args.first().map(String::as_str) {
        Some("gen-header") => gen_header(false),
        Some("check-header") => gen_header(true),
        Some("gen-icons") => icons::files(&root()).and_then(|files| return sync(&files, false, "gen-icons")),
        Some("check-icons") => icons::files(&root()).and_then(|files| return sync(&files, true, "gen-icons")),
        Some("dist") => gen_header(true)
            .and_then(|()| return icons::files(&root()))
            .and_then(|files| return sync(&files, true, "gen-icons"))
            .and_then(|()| return dist::dist(&root())),
        _ => {
            eprintln!("usage: cargo xtask <gen-header|check-header|gen-icons|check-icons|dist>");
            return ExitCode::FAILURE;
        }
    };
    match result {
        Ok(()) => return ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("error: {e}");
            return ExitCode::FAILURE;
        }
    }
}

fn root() -> PathBuf {
    return Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap().to_path_buf();
}

fn gen_header(check: bool) -> Result<(), String> {
    let root = root();
    let protocol_dir = root.join("crates/protocol");
    let component = root.join("firmware/components/protocol");

    let files = [
        (component.join("include/protocol.h"), protocol_header(&protocol_dir)?),
        (component.join("test/layout_check.c"), layout_check()),
        (component.join("test/test_vectors.h"), test_vectors()?),
        (root.join("firmware/version.txt"), format!("{}\n", env!("CARGO_PKG_VERSION"))),
    ];
    return sync(&files.map(|(path, content)| return (path, content.into_bytes())), check, "gen-header");
}

fn sync(files: &[(PathBuf, Vec<u8>)], check: bool, task: &str) -> Result<(), String> {
    let mut stale = Vec::new();
    for (path, content) in files {
        if fs::read(path).is_ok_and(|current| return current == *content) {
            continue;
        }
        if check {
            stale.push(path.display().to_string());
        } else {
            fs::create_dir_all(path.parent().unwrap()).map_err(|e| return e.to_string())?;
            fs::write(path, content).map_err(|e| format!("{}: {e}", path.display()))?;
            println!("wrote {}", path.display());
        }
    }
    if !stale.is_empty() {
        return Err(format!("out of date (run `cargo xtask {task}`): {}", stale.join(", ")));
    }
    if check {
        println!("generated files are up to date");
    }
    return Ok(());
}

fn protocol_header(protocol_dir: &Path) -> Result<String, String> {
    let mut config = cbindgen::Config::from_file(protocol_dir.join("cbindgen.toml"))?;
    for (name, _) in proto::WIRE_STRUCTS {
        config.export.include.push(name.to_string());
        config.export.rename.insert(name.to_string(), c_struct(name));
    }
    let mut after_include = format!(
        "\n#define PROTOCOL_APP_VERSION_MAJOR {}\n#define PROTOCOL_APP_VERSION_MINOR {}\n\
         #define PROTOCOL_APP_VERSION_PATCH {}\n\n",
        env!("CARGO_PKG_VERSION_MAJOR"),
        env!("CARGO_PKG_VERSION_MINOR"),
        env!("CARGO_PKG_VERSION_PATCH"),
    );
    for &(msg_type, name) in MsgType::ALL {
        writeln!(after_include, "#define PROTOCOL_MSG_TYPE_{} 0x{:02X}", screaming_snake(name), msg_type as u8)
            .unwrap();
    }
    let bindings = cbindgen::Builder::new()
        .with_config(config)
        .with_crate(protocol_dir)
        .with_after_include(after_include)
        .generate()
        .map_err(|e| return e.to_string())?;
    let mut out = Vec::new();
    bindings.write(&mut out);
    let text = String::from_utf8(out).map_err(|e| return e.to_string())?;
    // Keep the committed file identical on every OS.
    return Ok(text.replace("\r\n", "\n"));
}

fn layout_check() -> String {
    let mut out = String::from(
        "/* Generated by `cargo xtask gen-header` from crates/protocol. Do not edit by hand. */\n\
         #include \"protocol.h\"\n\n",
    );
    for (name, size) in proto::WIRE_STRUCTS {
        writeln!(out, "_Static_assert(sizeof({}) == {size}, \"layout differs from crates/protocol\");", c_struct(name))
            .unwrap();
    }
    return out;
}

/// `DeviceInfo` → `protocol_device_info_t`.
fn c_struct(name: &str) -> String {
    return format!("protocol_{}_t", screaming_snake(name).to_lowercase());
}

/// The firmware's C codec must produce and parse exactly these bytes.
fn test_vectors() -> Result<String, String> {
    let mut keys = proto::KeyboardState::default();
    keys.set(0x04, true); // A
    keys.set(0xE1, true); // Left Shift
    let audio_head = proto::AudioHeader { first_frame_number: 0x01020304 };
    let pcm: Vec<u8> = (0..292u32).map(|i| return (i * 7 % 256) as u8).collect();
    let log_head = proto::LogHeader { level: proto::LOG_INFO };

    let vectors = [
        ("hello", Msg::Hello, 1u16),
        ("keyboard", Msg::KeyboardState(keys), 2),
        ("log", Msg::Log(log_head, b"kvmate"), 3),
        ("audio", Msg::AudioPlayback(audio_head, &pcm), 0xFFFF),
        ("release_all", Msg::ReleaseAll, 0x1234),
    ];

    let mut out = String::from(
        "/* Generated by `cargo xtask gen-header` from crates/protocol. Do not edit by hand. */\n\
         /* Frames encoded by the Rust code, for the firmware's self-test. */\n\
         #pragma once\n\n#include <stdint.h>\n\n\
         /* A message and the bytes of its frame on the wire. */\n\
         typedef struct {\n    uint8_t msg_type;\n    uint16_t seq;\n    const uint8_t *payload;\n    uint16_t payload_len;\n    const uint8_t *wire;\n    uint16_t wire_len;\n} test_vector_t;\n\n",
    );
    for (name, msg, seq) in &vectors {
        let mut wire = vec![0u8; proto::MAX_ENCODED_LEN];
        let n = msg.encode(*seq, &mut wire).map_err(|e| return format!("{e:?}"))?;
        wire.truncate(n);
        write_array(&mut out, &format!("tv_{name}_payload"), &msg.parts().concat());
        write_array(&mut out, &format!("tv_{name}_wire"), &wire);
    }
    out.push_str("static const test_vector_t TEST_VECTORS[] = {\n");
    for (name, msg, seq) in &vectors {
        writeln!(
            out,
            "    {{ 0x{:02X}, 0x{seq:04X}, tv_{name}_payload, {}, tv_{name}_wire, sizeof(tv_{name}_wire) }},",
            msg.msg_type() as u8,
            msg.parts().concat().len()
        )
        .unwrap();
    }
    out.push_str("};\n\n#define TEST_VECTOR_COUNT (sizeof(TEST_VECTORS) / sizeof(TEST_VECTORS[0]))\n\n");
    secure_vectors(&mut out)?;
    // Every array ends with a blank line; the file does not.
    out.pop();
    return Ok(out);
}

/// The firmware's Wi-Fi encryption must derive the same keys and produce the same bytes.
fn secure_vectors(out: &mut String) -> Result<(), String> {
    let key: secure::PairingKey = std::array::from_fn(|i| return (i as u8).wrapping_mul(29).wrapping_add(7));
    let hub_nonce: [u8; 16] = std::array::from_fn(|i| return 0xA0 + i as u8);
    let board_nonce: [u8; 16] = std::array::from_fn(|i| return 0x30 + 3 * i as u8);
    let hb = proto::Heartbeat { flags: proto::HEARTBEAT_FLAG_HELLO_ANSWERED };
    let mut plain = vec![0u8; proto::MAX_ENCODED_LEN];
    let n = Msg::Heartbeat(hb).encode(7, &mut plain).map_err(|e| return format!("{e:?}"))?;
    plain.truncate(n);

    let mut hub = secure::Session::for_hub(&key, &hub_nonce, &board_nonce);
    let mut board = secure::Session::for_board(&key, &hub_nonce, &board_nonce);
    let mut dgram = vec![0u8; secure::DGRAM_MAX_LEN];
    let len = hub.tx.seal(&plain, &mut dgram).ok_or("seal")?;
    let to_board = dgram[..len].to_vec();
    let len = board.tx.seal(&plain, &mut dgram).ok_or("seal")?;
    let to_hub = dgram[..len].to_vec();

    out.push_str("/* Wi-Fi datagram encryption (crates/protocol/src/secure.rs). */\n");
    write_array(out, "tv_secure_key", &key);
    write_array(out, "tv_secure_hub_nonce", &hub_nonce);
    write_array(out, "tv_secure_board_nonce", &board_nonce);
    write_array(out, "tv_secure_key_id", &secure::key_id(&key));
    write_array(out, "tv_secure_reply_mac", &secure::reply_mac(&key, &hub_nonce, &board_nonce));
    write_array(out, "tv_secure_plain", &plain);
    write_array(out, "tv_secure_to_board", &to_board);
    write_array(out, "tv_secure_to_hub", &to_hub);
    return Ok(());
}

fn write_array(out: &mut String, name: &str, bytes: &[u8]) {
    // Zero-length arrays are not valid C; keep one dummy byte and rely on the explicit length.
    let data: &[u8] = if bytes.is_empty() { &[0] } else { bytes };
    writeln!(out, "static const uint8_t {name}[{}] = {{", data.len()).unwrap();
    for chunk in data.chunks(16) {
        let line: Vec<String> = chunk.iter().map(|b| format!("0x{b:02X}")).collect();
        writeln!(out, "    {},", line.join(", ")).unwrap();
    }
    out.push_str("};\n\n");
}

/// `KeyboardState` → `KEYBOARD_STATE`.
fn screaming_snake(name: &str) -> String {
    let mut out = String::new();
    for (i, c) in name.chars().enumerate() {
        if c.is_ascii_uppercase() && i > 0 {
            out.push('_');
        }
        out.push(c.to_ascii_uppercase());
    }
    return out;
}
